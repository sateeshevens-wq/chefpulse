#!/usr/bin/env bash
set -euo pipefail

: "${CHEFPULSE_KEYSTORE_PATH:?CHEFPULSE_KEYSTORE_PATH is required}"
: "${CHEFPULSE_KEYSTORE_PASSWORD:?CHEFPULSE_KEYSTORE_PASSWORD is required}"
: "${CHEFPULSE_KEY_ALIAS:?CHEFPULSE_KEY_ALIAS is required}"
: "${CHEFPULSE_KEY_PASSWORD:?CHEFPULSE_KEY_PASSWORD is required}"

BUILD_FILE="android/app/build.gradle"

if [[ ! -f "$BUILD_FILE" ]]; then
  echo "ERROR: $BUILD_FILE was not generated by Capacitor."
  exit 1
fi

python3 - <<'PY'
from pathlib import Path
import os

path = Path("android/app/build.gradle")
text = path.read_text()

if "signingConfigs" in text and "CHEFPULSE_KEYSTORE_PATH" in text:
    print("ChefPulse release signing is already configured.")
    raise SystemExit(0)

signing_block = '''\nsigningConfigs {\n    release {\n        storeFile file(System.getenv("CHEFPULSE_KEYSTORE_PATH"))\n        storePassword System.getenv("CHEFPULSE_KEYSTORE_PASSWORD")\n        keyAlias System.getenv("CHEFPULSE_KEY_ALIAS")\n        keyPassword System.getenv("CHEFPULSE_KEY_PASSWORD")\n    }\n}\n'''

if "buildTypes {" not in text:
    raise SystemExit("ERROR: Could not locate buildTypes block in android/app/build.gradle")

text = text.replace("buildTypes {", signing_block + "\nbuildTypes {", 1)

needle = "release {"
start = text.find(needle, text.find("buildTypes {"))
if start == -1:
    raise SystemExit("ERROR: Could not locate release build type")

brace = text.find("{", start)
depth = 0
end = None
for i in range(brace, len(text)):
    if text[i] == "{":
        depth += 1
    elif text[i] == "}":
        depth -= 1
        if depth == 0:
            end = i
            break
if end is None:
    raise SystemExit("ERROR: Could not parse release build type")

release_body = text[brace + 1:end]
if "signingConfig signingConfigs.release" not in release_body:
    release_body = "\n        signingConfig signingConfigs.release" + release_body
    text = text[:brace + 1] + release_body + text[end:]

path.write_text(text)
print("ChefPulse release signing configured in android/app/build.gradle")
PY

# Verify that the generated Gradle file contains the intended signing configuration.
grep -q 'signingConfig signingConfigs.release' "$BUILD_FILE"
grep -q 'CHEFPULSE_KEYSTORE_PATH' "$BUILD_FILE"

echo "ChefPulse Android release signing configuration verified."
